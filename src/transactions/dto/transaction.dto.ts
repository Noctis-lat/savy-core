import { ApiProperty, ApiPropertyOptional } from "@nestjs/swagger";
import { Type } from "class-transformer";
import {
	IsBooleanString,
	IsDateString,
	IsEnum,
	IsInt,
	IsNotEmpty,
	IsNumber,
	IsOptional,
	IsString,
	Max,
	MaxLength,
	Min,
} from "class-validator";
import { PERIODS } from "../../common/utils/period.util";

/** Every transaction type, including system-generated ones (used for reads and filters). */
enum TransactionType {
	INCOME = "INCOME",
	EXPENSE = "EXPENSE",
	TRANSFER = "TRANSFER",
	PAYMENT = "PAYMENT",
	INSTALLMENT = "INSTALLMENT",
}

/**
 * Types a user can create or switch to. INSTALLMENT is system-only: those rows are
 * generated by the statement engine at each cut.
 */
enum UserTransactionType {
	INCOME = "INCOME",
	EXPENSE = "EXPENSE",
	TRANSFER = "TRANSFER",
	PAYMENT = "PAYMENT",
}

enum TransactionSortBy {
	date = "date",
	amount = "amount",
	createdAt = "createdAt",
}

enum SortOrder {
	asc = "asc",
	desc = "desc",
}

enum InstallmentPlanType {
	MSI = "MSI",
	MSCI = "MSCI",
}

enum CommissionType {
	ANNUAL_FEE = "ANNUAL_FEE",
	LATE_PAYMENT = "LATE_PAYMENT",
	CASH_ADVANCE = "CASH_ADVANCE",
}

export class CreateTransactionDto {
	@ApiProperty({ example: "account-uuid", description: "Source account ID (where money leaves)" })
	@IsString()
	@IsNotEmpty()
	accountId!: string;

	@ApiPropertyOptional({
		example: "destination-uuid",
		description:
			"Destination account ID (required for TRANSFER and PAYMENT, null for INCOME/EXPENSE)",
	})
	@IsOptional()
	@IsString()
	destinationAccountId?: string | null;

	@ApiPropertyOptional({
		example: "category-uuid",
		description: "Category ID (optional, for INCOME/EXPENSE categorization)",
	})
	@IsOptional()
	@IsString()
	categoryId?: string;

	@ApiProperty({
		enum: UserTransactionType,
		example: "EXPENSE",
		description: "Transaction type (INSTALLMENT is system-only and rejected)",
	})
	@IsEnum(UserTransactionType)
	type!: UserTransactionType;

	@ApiProperty({ example: 1500.0, description: "Transaction amount" })
	@Type(() => Number)
	@IsNumber()
	@Min(0)
	amount!: number;

	@ApiPropertyOptional({ example: "Grocery shopping", description: "Short description" })
	@IsOptional()
	@IsString()
	@MaxLength(200)
	description?: string;

	@ApiPropertyOptional({ example: "Weekly groceries at Walmart", description: "Detailed note" })
	@IsOptional()
	@IsString()
	@MaxLength(1000)
	note?: string;

	@ApiPropertyOptional({
		example: "2026-07-28T12:00:00.000Z",
		description: "Transaction date (defaults to now)",
	})
	@IsOptional()
	@IsDateString()
	date?: string;

	@ApiPropertyOptional({
		example: 12,
		description: "Number of months for MSI/MSCI installment plan (1-36)",
	})
	@IsOptional()
	@Type(() => Number)
	@IsInt()
	@Min(1)
	@Max(36)
	msiMonths?: number;

	@ApiPropertyOptional({
		enum: InstallmentPlanType,
		example: "MSI",
		description: "Installment plan type (MSI = sin intereses, MSCI = con intereses)",
	})
	@IsOptional()
	@IsEnum(InstallmentPlanType)
	msiType?: InstallmentPlanType;

	@ApiPropertyOptional({
		example: 0.12,
		description: "Promotional interest rate for MSCI plans (e.g. 0.12 = 12%)",
	})
	@IsOptional()
	@Type(() => Number)
	@IsNumber()
	msiRate?: number;

	@ApiPropertyOptional({
		enum: CommissionType,
		example: "ANNUAL_FEE",
		description:
			"Commission type for typed EXPENSE transactions (ANNUAL_FEE, LATE_PAYMENT, CASH_ADVANCE)",
	})
	@IsOptional()
	@IsEnum(CommissionType)
	commissionType?: CommissionType;
}


export class QueryTransactionsDto {
	@ApiPropertyOptional({
		example: "account-uuid",
		description: "Filter by account (source or destination)",
	})
	@IsOptional()
	@IsString()
	accountId?: string;

	@ApiPropertyOptional({
		enum: TransactionType,
		example: "EXPENSE",
		description: "Filter by transaction type",
	})
	@IsOptional()
	@IsEnum(TransactionType)
	type?: TransactionType;

	@ApiPropertyOptional({ example: "category-uuid", description: "Filter by category" })
	@IsOptional()
	@IsString()
	categoryId?: string;

	@ApiPropertyOptional({
		example: "bank-uuid",
		description: "Filter by accounts belonging to this bank",
	})
	@IsOptional()
	@IsString()
	bankId?: string;

	@ApiPropertyOptional({
		example: "grocery",
		description: "Partial case-insensitive search in description",
	})
	@IsOptional()
	@IsString()
	search?: string;

	@ApiPropertyOptional({
		example: "2026-07-01T00:00:00.000Z",
		description: "Start date (ISO 8601)",
	})
	@IsOptional()
	@IsDateString()
	from?: string;

	@ApiPropertyOptional({ example: "2026-07-31T23:59:59.999Z", description: "End date (ISO 8601)" })
	@IsOptional()
	@IsDateString()
	to?: string;

	@ApiPropertyOptional({ example: 1, description: "Page number (default 1)" })
	@IsOptional()
	@Type(() => Number)
	@IsInt()
	@Min(1)
	page?: number;

	@ApiPropertyOptional({ example: 50, description: "Items per page (default 50, max 100)" })
	@IsOptional()
	@Type(() => Number)
	@IsInt()
	@Min(1)
	limit?: number;

	@ApiPropertyOptional({
		enum: TransactionSortBy,
		example: "date",
		default: "date",
		description: "Sort field",
	})
	@IsOptional()
	@IsEnum(TransactionSortBy)
	sortBy?: TransactionSortBy;

	@ApiPropertyOptional({
		enum: SortOrder,
		example: "desc",
		default: "desc",
		description: "Sort order",
	})
	@IsOptional()
	@IsEnum(SortOrder)
	order?: SortOrder;

	@ApiPropertyOptional({
		example: "true",
		default: "false",
		description:
			'Include financial info summary (netWorth, liquidity, debt) in the response (accepts "true"/"false")',
	})
	@IsOptional()
	@IsBooleanString()
	info?: string;

	@ApiPropertyOptional({
		enum: PERIODS,
		default: "month",
		description:
			"Filter transactions by period. When set, overrides from/to with the computed date range. Defaults to all transactions if omitted.",
	})
	@IsOptional()
	@IsString()
	period?: string;
}
